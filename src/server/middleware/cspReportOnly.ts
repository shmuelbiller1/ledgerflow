/**
 * S-23: Content-Security-Policy tightened (no unsafe-inline where possible); report-only first
 * 
 * This module provides a CSP middleware that can be deployed in report-only mode
 * first, then switched to enforcement mode once validated.
 * 
 * The tightened CSP removes 'unsafe-inline' for script-src and style-src where possible,
 * using nonces instead. This provides better security against XSS attacks.
 */

import type { Request, Response, NextFunction } from 'express';
import { randomBytes } from 'crypto';

declare module 'express' {
  interface Request {
    /** CSP nonce generated by the report-only / enforcement middleware (S-23) */
    cspNonce?: string;
  }
}

/**
 * Configuration for CSP report-only mode
 */
export interface CspReportOnlyConfig {
  /** Whether to use report-only mode (Content-Security-Policy-Report-Only) */
  reportOnly: boolean;
  /** URL to send CSP violation reports to */
  reportUri?: string;
  /** Whether to use nonces for inline scripts/styles */
  useNonces: boolean;
  /** Additional allowed domains */
  additionalDomains?: {
    script?: string[];
    style?: string[];
    connect?: string[];
    img?: string[];
    font?: string[];
    frame?: string[];
  };
}

/**
 * Default configuration for report-only mode
 */
export const defaultCspReportOnlyConfig: CspReportOnlyConfig = {
  reportOnly: true,
  reportUri: undefined, // Can be set to a violation reporting endpoint
  useNonces: true,
  additionalDomains: {}
};

/**
 * Generate CSP header value with report-only option
 */
export function generateCspHeader(config: Partial<CspReportOnlyConfig> = {}): string {
  const mergedConfig: CspReportOnlyConfig = {
    ...defaultCspReportOnlyConfig,
    ...config
  };
  const directives: string[] = [
    "default-src 'self'",
    // Script sources - use nonces instead of unsafe-inline
    mergedConfig.useNonces 
      ? "script-src 'self' 'nonce-${generateNonce()}' https://cdn.plaid.com"
      : "script-src 'self' 'unsafe-inline' https://cdn.plaid.com",
    
    // Style sources - use nonces instead of unsafe-inline
    mergedConfig.useNonces
      ? "style-src 'self' 'nonce-${generateNonce()}' https://fonts.googleapis.com"
      : "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
    
    "img-src 'self' data: blob: https:",
    `connect-src 'self' ${getSupabaseUrls().join(' ')} https://*.plaid.com https://*.googleapis.com`,
    "font-src 'self' data: https://fonts.gstatic.com",
    "frame-src 'self' https://*.stripe.com https://cdn.plaid.com",
    "frame-ancestors 'self'",
    "form-action 'self'",
    "base-uri 'self'",
    "object-src 'none'",
    "worker-src 'self' blob:",
    "manifest-src 'self'"
  ];

  // Add additional domains if specified
  if (mergedConfig.additionalDomains?.script?.length) {
    directives.push(`script-src ${mergedConfig.additionalDomains.script.join(' ')}`);
  }
  if (mergedConfig.additionalDomains?.style?.length) {
    directives.push(`style-src ${mergedConfig.additionalDomains.style.join(' ')}`);
  }
  if (mergedConfig.additionalDomains?.connect?.length) {
    directives.push(`connect-src ${mergedConfig.additionalDomains.connect.join(' ')}`);
  }
  if (mergedConfig.additionalDomains?.img?.length) {
    directives.push(`img-src ${mergedConfig.additionalDomains.img.join(' ')}`);
  }
  if (mergedConfig.additionalDomains?.font?.length) {
    directives.push(`font-src ${mergedConfig.additionalDomains.font.join(' ')}`);
  }
  if (mergedConfig.additionalDomains?.frame?.length) {
    directives.push(`frame-src ${mergedConfig.additionalDomains.frame.join(' ')}`);
  }

  // Add report-uri if specified
  if (mergedConfig.reportUri) {
    directives.push(`report-uri ${mergedConfig.reportUri}`);
    directives.push(`report-to csp-endpoint`);
  }

  return directives.join('; ');
}

/**
 * Generate a cryptographic nonce for CSP
 */
export function generateNonce(): string {
  return randomBytes(16).toString('base64');
}

/**
 * Get Supabase URLs for connect-src
 */
function getSupabaseUrls(): string[] {
  const url = process.env.SUPABASE_URL || 'https://sbxxbbscuwmlkvcvkbxi.supabase.co';
  return [
    url.replace(/^http/, 'https'),
    url.replace(/^http/, 'wss')
  ];
}

/**
 * Generate all security headers with report-only CSP
 */
export function generateReportOnlySecurityHeaders(config: Partial<CspReportOnlyConfig> = {}): Record<string, string> {
  const mergedConfig: CspReportOnlyConfig = {
    ...defaultCspReportOnlyConfig,
    ...config
  };

  const headers: Record<string, string> = {};

  // Generate CSP
  const csp = generateCspHeader(mergedConfig);
  const headerKey = mergedConfig.reportOnly 
    ? 'Content-Security-Policy-Report-Only' 
    : 'Content-Security-Policy';
  headers[headerKey] = csp;

  // Add other security headers
  headers['Strict-Transport-Security'] = 'max-age=31536000; includeSubDomains; preload';
  headers['X-Content-Type-Options'] = 'nosniff';
  headers['X-Frame-Options'] = 'SAMEORIGIN';
  headers['Referrer-Policy'] = 'strict-origin-when-cross-origin';
  headers['Permissions-Policy'] = [
    'accelerometer=()',
    'camera=()',
    'geolocation=()',
    'gyroscope=()',
    'magnetometer=()',
    'microphone=()',
    'payment=()',
    'usb=()'
  ].join(', ');
  headers['X-XSS-Protection'] = '1; mode=block';
  headers['Cross-Origin-Embedder-Policy'] = 'require-corp';
  headers['Cross-Origin-Opener-Policy'] = 'same-origin';
  headers['Cross-Origin-Resource-Policy'] = 'same-origin';

  return headers;
}

/**
 * Express middleware for CSP report-only mode
 * 
 * S-23: Deploys tightened CSP in report-only mode first
 */
export function cspReportOnlyMiddleware(config: Partial<CspReportOnlyConfig> = {}): (req: Request, res: Response, next: NextFunction) => void {
  const headers = generateReportOnlySecurityHeaders(config);

  return (req: Request, res: Response, next: NextFunction) => {
    // Apply all security headers
    for (const [key, value] of Object.entries(headers)) {
      res.setHeader(key, value);
    }

    // If using nonces, generate and pass to the view
    if (config.useNonces !== false) {
      const nonce = generateNonce();
      req.cspNonce = nonce;
    }

    next();
  };
}

/**
 * Express middleware for enforcement mode (after report-only validation)
 */
export function cspEnforcementMiddleware(config: Partial<CspReportOnlyConfig> = {}): (req: Request, res: Response, next: NextFunction) => void {
  const headers = generateReportOnlySecurityHeaders({
    ...config,
    reportOnly: false
  });

  return (req: Request, res: Response, next: NextFunction) => {
    for (const [key, value] of Object.entries(headers)) {
      res.setHeader(key, value);
    }

    if (config.useNonces !== false) {
      const nonce = generateNonce();
      req.cspNonce = nonce;
    }

    next();
  };
}

/**
 * CSP violation reporting endpoint
 * 
 * S-23: Collects CSP violation reports for analysis
 */
export function createCspViolationEndpoint() {
  return async (req: Request, res: Response) => {
    try {
      if (req.method !== 'POST') {
        return res.status(405).json({ error: 'Method not allowed' });
      }

      const report = req.body;
      
      // Validate it's a CSP violation report
      if (!report || !report['csp-report']) {
        return res.status(400).json({ error: 'Invalid CSP violation report' });
      }

      const cspReport = report['csp-report'];
      
      // Log the violation
      console.warn('[CSP Violation Report]:', {
        blockedUri: cspReport['blocked-uri'],
        violatedDirective: cspReport['violated-directive'],
        originalPolicy: cspReport['original-policy'],
        sourceFile: cspReport['source-file'],
        lineNumber: cspReport['line-number'],
        columnNumber: cspReport['column-number']
      });

      // Store in database for analysis
      const db = (await import('../db/firestore')).getDb();
      const docRef = db.collection('cspViolations').doc();
      await docRef.set({
        report: cspReport,
        timestamp: new Date().toISOString(),
        userAgent: req.headers['user-agent'],
        ip: req.ip,
        path: req.path
      });

      res.status(204).end();
    } catch (err) {
      console.error('[CSP Violation Endpoint] Error:', err);
      res.status(500).json({ error: 'Failed to process CSP violation report' });
    }
  };
}

/**
 * CSP configuration validator
 * 
 * S-23: Validates that the CSP won't break required functionality
 */
export function validateCspConfiguration(csp: string): {
  valid: boolean;
  warnings: string[];
  errors: string[];
} {
  const warnings: string[] = [];
  const errors: string[] = [];

  // Check for unsafe-inline
  if (csp.includes("'unsafe-inline'")) {
    warnings.push('CSP contains \'unsafe-inline\' - consider using nonces for better security');
  }

  // Check for required domains
  const requiredDomains = [
    'https://cdn.plaid.com',
    'https://fonts.googleapis.com',
    'https://fonts.gstatic.com',
    'https://*.stripe.com'
  ];

  for (const domain of requiredDomains) {
    if (!csp.includes(domain)) {
      errors.push(`Required domain not in CSP: ${domain}`);
    }
  }

  // Check for required directives
  const requiredDirectives = [
    'default-src',
    'script-src',
    'style-src',
    'img-src',
    'connect-src',
    'font-src',
    'frame-src'
  ];

  for (const directive of requiredDirectives) {
    if (!csp.includes(`${directive} `) && !csp.includes(`${directive}'`)) {
      errors.push(`Required directive not in CSP: ${directive}`);
    }
  }

  return {
    valid: errors.length === 0,
    warnings,
    errors
  };
}

/**
 * Generate a migration report for switching from report-only to enforcement
 */
export function generateCspMigrationReport(
  violations: Array<{ report?: Record<string, unknown> }>
): string {
  const reportLines: string[] = [
    '# CSP Migration Report',
    '',
    `**Date:** ${new Date().toISOString()}`,
    '',
    '## Summary',
    '',
    `Total violations collected: ${violations.length}`,
    '',
    '## Violation Details',
    ''
  ];

  if (violations.length === 0) {
    reportLines.push('✅ No CSP violations detected. Safe to switch to enforcement mode.');
  } else {
    reportLines.push('⚠️ CSP violations detected. Review before switching to enforcement mode.');
    reportLines.push('');
    reportLines.push('| Blocked URI | Violated Directive | Source File | Line |');
    reportLines.push('|-------------|-------------------|------------|------|');
    
    for (const violation of violations) {
      const cspReport = violation.report || {};
      reportLines.push(`| ${cspReport['blocked-uri'] || 'N/A'} | ${cspReport['violated-directive'] || 'N/A'} | ${cspReport['source-file'] || 'N/A'} | ${cspReport['line-number'] || 'N/A'} |`);
    }
  }

  reportLines.push('');
  reportLines.push('## Recommendations');
  reportLines.push('');
  
  if (violations.length === 0) {
    reportLines.push('1. Switch CSP from report-only to enforcement mode');
    reportLines.push('2. Monitor for any new violations');
    reportLines.push('3. Consider implementing nonce generation in the application');
  } else {
    reportLines.push('1. Review each violation and determine if it\'s legitimate');
    reportLines.push('2. For legitimate violations, update the CSP to allow the blocked resource');
    reportLines.push('3. For false positives, investigate why the resource is being blocked');
    reportLines.push('4. Consider implementing nonce generation for inline scripts/styles');
  }

  return reportLines.join('\n');
}
